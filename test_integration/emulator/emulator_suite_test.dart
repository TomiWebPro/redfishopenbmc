/// End-to-end suite against the **real DMTF Redfish-Mockup-Server** running
/// over HTTPS (issue EMU-1/EMU-2/EMU-3 in FUTUREWORK.md).
///
/// Run with `tool/emulator/run_tests.sh` (or manually):
///
/// ```bash
/// flutter test test_integration/emulator \
///   --dart-define=REDFISH_EMULATOR_URL=https://127.0.0.1:8443
/// ```
///
/// The suite reads the emulator base URL from
/// `REDFISH_EMULATOR_URL` (a `String.fromEnvironment` define). When the define
/// is absent the tests **skip** so plain `flutter test` never requires the
/// emulator and never touches the network.
///
/// TLS: the emulator uses a short-lived self-signed cert generated by
/// `tool/emulator/run_tests.sh`. `allowSelfSigned: true` is used **only** in
/// this test profile (runbook §3.1 / EMU-6); production code paths remain
/// TLS-validating.
const String emulatorUrl = String.fromEnvironment('REDFISH_EMULATOR_URL');

/// True when the emulator URL was supplied; tests `markTestSkipped` otherwise.
bool get _emulatorConfigured => emulatorUrl.isNotEmpty;

/// Parses [emulatorUrl] (e.g. `https://127.0.0.1:8443`) into a profile.
///
/// The last path segment of the URL is treated as the port; the remainder as
/// the host. Only `https` is supported (TLS-first; mirror of the production
/// contract). [allowSelfSigned] is true here — this is the test-only profile.
ConnectionProfile emulatorProfile({
  String username = 'root',
  String password = 'calvin',
  bool preferSessionAuth = true,
}) {
  final Uri uri = Uri.parse(emulatorUrl);
  return ConnectionProfile(
    host: uri.host,
    port: uri.port,
    scheme: uri.scheme == 'http' ? 'https' : uri.scheme,
    allowSelfSigned: true,
    username: username,
    password: password,
    preferSessionAuth: preferSessionAuth,
  );
}

/// Direct unauthenticated client to the emulator (service-root probes only).
RedfishClient rawClient() =>
    RedfishClient(profile: emulatorProfile(preferSessionAuth: false));

