/// End-to-end suite against the **real DMTF Redfish-Mockup-Server** running
/// over HTTPS (issue EMU-1/EMU-2/EMU-3 in FUTUREWORK.md).
///
/// Run with `tool/emulator/run_tests.sh` (or manually):
///
/// ```bash
/// flutter test test_integration/emulator \
///   --dart-define=REDFISH_EMULATOR_URL=https://127.0.0.1:8443
/// ```
///
/// The suite reads the emulator base URL from
/// `REDFISH_EMULATOR_URL` (a `String.fromEnvironment` define). When the define
/// is absent the tests **skip** so plain `flutter test` never requires the
/// emulator and never touches the network.
///
/// TLS: the emulator uses a short-lived self-signed cert generated by
/// `tool/emulator/run_tests.sh`. `allowSelfSigned: true` is used **only** in
/// this test profile (runbook §3.1 / EMU-6); production code paths remain
/// TLS-validating.
const String emulatorUrl = String.fromEnvironment('REDFISH_EMULATOR_URL');

/// True when the emulator URL was supplied; tests `markTestSkipped` otherwise.
bool get _emulatorConfigured => emulatorUrl.isNotEmpty;

/// Parses [emulatorUrl] (e.g. `https://127.0.0.1:8443`) into a profile.
///
/// The last path segment of the URL is treated as the port; the remainder as
/// the host. Only `https` is supported (TLS-first; mirror of the production
/// contract). [allowSelfSigned] is true here — this is the test-only profile.
ConnectionProfile emulatorProfile({
  String username = 'root',
  String password = 'calvin',
  bool preferSessionAuth = true,
}) {
  final Uri uri = Uri.parse(emulatorUrl);
  return ConnectionProfile(
    host: uri.host,
    port: uri.port,
    scheme: uri.scheme == 'http' ? 'https' : uri.scheme,
    allowSelfSigned: true,
    username: username,
    password: password,
    preferSessionAuth: preferSessionAuth,
  );
}

/// Direct unauthenticated client to the emulator (service-root probes only).
RedfishClient rawClient() =>
    RedfishClient(profile: emulatorProfile(preferSessionAuth: false));

void main() {
  if (!_emulatorConfigured) {
    test('emulator suite skipped (REDFISH_EMULATOR_URL not set)', () {
      markTestSkipped(
        'Set --dart-define=REDFISH_EMULATOR_URL=https://127.0.0.1:8443 '
        '(see tool/emulator/run_tests.sh) to run the emulator suite.',
      );
    });
    return;
  }

  group('emulator: service root + discovery', () {
    test('service root is reachable and self-describing', () async {
      final RedfishClient client = rawClient();
      final Map<String, dynamic> root = await client.getJson('/redfish/v1/');
      expect(root['@odata.id'], '/redfish/v1/');
      expect(root['RedfishVersion'], isA<String>());
      expect(root['Systems'], isA<Map<dynamic, dynamic>>());
      expect(root['Chassis'], isA<Map<dynamic, dynamic>>());
      expect(root['Managers'], isA<Map<dynamic, dynamic>>());
    });

    test('discovery engine performs BFS and builds the feature map', () async {
      final AuthManager manager = AuthManager(storage: InMemoryStorage());
      await manager.login('em1', emulatorProfile());
      final RedfishClient client = manager.clientFor('em1')!;

      final SystemFeatures features =
          await DiscoveryEngine().discover(client, 'em1');

      // DMTF public-rackmount1 mockup capabilities (verified upstream).
      expect(features.powerControl, isTrue,
          reason: '#ComputerSystem.Reset action is present in the mockup');
      expect(features.kvm, isTrue,
          reason: 'Manager GraphicalConsole ServiceEnabled=true');
      expect(features.kvmType, 'GraphicalConsole');
      expect(features.sensorMonitoring, isTrue,
          reason: 'Chassis exposes Thermal/Sensors');
      expect(features.sensorCount, greaterThan(0));
      expect(features.firmwareUpdate, isTrue,
          reason: 'UpdateService is present');
      expect(features.managers, greaterThan(0));
      expect(features.chassis, greaterThan(0));
      expect(features.raw, isNotEmpty);
    });
  });

  group('emulator: feature services', () {
    late AuthManager manager;
    late RedfishClient client;

    setUpAll(() async {
      manager = AuthManager(storage: InMemoryStorage());
      await manager.login('em1', emulatorProfile());
      client = manager.clientFor('em1')!;
    });

    tearDownAll(() async {
      await manager.logout('em1');
    });

    test('sensors: Thermal payload parses temperatures + fans', () async {
      final List<ChassisSensors> all =
          await SensorsService(client: client, systemId: 'em1').fetchAll();
      expect(all, isNotEmpty);
      final ChassisSensors chassis = all.first;
      expect(chassis.thermal, isNotEmpty);
      expect(
        chassis.thermal.any((ThermalReading t) =>
            t.name == 'CPU1 Temp' && t.readingCelsius == 41.0),
        isTrue,
      );
      expect(chassis.fans, isNotEmpty);
    });

    test('firmware: UpdateService + FirmwareInventory enumerate inventory',
        () async {
      final FirmwareService svc = FirmwareService(
        client: client,
        systemId: 'em1',
      );
      final UpdateServiceInfo info = await svc.fetchUpdateService();
      expect(info.serviceEnabled, isTrue);
      // DMTF mockup ships BMC + SS + BIOS firmware entries.
      expect(info.inventory.length, greaterThanOrEqualTo(3));
      expect(
        info.inventory
            .where((FirmwareInventoryItem i) =>
                i.version != null && i.version!.isNotEmpty)
            .isNotEmpty,
        isTrue,
      );
    });

    test('kvm: graphical console detected from manager', () async {
      final List<KvmConsole> consoles =
          await KvmService(client: client, systemId: 'em1').fetchConsoles();
      expect(consoles, isNotEmpty);
      expect(
        consoles.any((KvmConsole c) => c.type == KvmConsoleType.graphical),
        isTrue,
      );
      final KvmConsole? primary =
          await KvmService(client: client, systemId: 'em1')
              .fetchPrimaryConsole();
      expect(primary, isNotNull);
      expect(primary!.type, KvmConsoleType.graphical);
    });

    test('systems: ComputerSystem exposes full inventory fields', () async {
      final Map<String, dynamic> sys =
          await client.getJson('/redfish/v1/Systems/437XR1138R2');
      expect(sys['@odata.id'], '/redfish/v1/Systems/437XR1138R2');
      expect(sys['Model'], '3500');
      expect(sys['Manufacturer'], 'Contoso');
      expect(sys['SerialNumber'], '437XR1138R2');
      expect(sys['PowerState'], 'On');
      final Map<dynamic, dynamic> status =
          sys['Status'] as Map<dynamic, dynamic>;
      expect(status['State'], 'Enabled');
      expect(status['Health'], 'OK');
      // Reset action advertises its AllowableValues (the allow-list the
      // client gates reset types on — DOCS-4 / #022).
      final Map<dynamic, dynamic> actions =
          sys['Actions'] as Map<dynamic, dynamic>;
      final Map<dynamic, dynamic> reset =
          actions['#ComputerSystem.Reset'] as Map<dynamic, dynamic>;
      expect(reset['target'],
          '/redfish/v1/Systems/437XR1138R2/Actions/ComputerSystem.Reset');
      expect(reset['ResetType@Redfish.AllowableValues'], isA<List<dynamic>>());
    });

    test('firmware: UpdateServiceInfo exposes the HTTP-push URI (DOCS-4)',
        () async {
      final FirmwareService svc = FirmwareService(
        client: client,
        systemId: 'em1',
      );
      final UpdateServiceInfo info = await svc.fetchUpdateService();
      expect(info.serviceEnabled, isTrue);
      expect(info.httpPushUri, '/FWUpdate',
          reason: 'the DMTF mockup advertises HttpPushUri; OpenBMC bmcweb '
              'firmware updates are HTTP-push (HttpPushUri), not SimpleUpdate '
              '(DOCS-4, FUTUREWORK #008/#020)');
      expect(info.inventory, isNotEmpty);
    });
  });

  group('emulator: auth (EMU-3)', () {
    test('session login mints X-Auth-Token and reuses it', () async {
      final AuthManager manager = AuthManager(storage: InMemoryStorage());
      final Session session = await manager.login('em1', emulatorProfile());
      expect(session.token, isNotEmpty);
      expect(manager.isAuthenticated('em1'), isTrue);

      final RedfishClient client = manager.clientFor('em1')!;
      final Map<String, dynamic> root = await client.getJson('/redfish/v1/');
      expect(root['@odata.id'], '/redfish/v1/');

      await manager.logout('em1');
      expect(manager.isAuthenticated('em1'), isFalse,
          reason: 'logout must purge the session + stored token');
    });

    test('basic auth header works against the emulator', () async {
      final AuthManager manager = AuthManager(storage: InMemoryStorage());
      await manager.login(
        'em-basic',
        emulatorProfile(preferSessionAuth: false),
      );
      expect(manager.isAuthenticated('em-basic'), isTrue);
      final RedfishClient client = manager.clientFor('em-basic')!;
      final Map<String, dynamic> root = await client.getJson('/redfish/v1/');
      expect(root['@odata.id'], '/redfish/v1/');
      await manager.logout('em-basic');
    });
  });

  group('emulator: power actions + error mapping (EMU-3)', () {
    late AuthManager manager;
    late RedfishClient client;

    setUpAll(() async {
      manager = AuthManager(storage: InMemoryStorage());
      await manager.login('em1', emulatorProfile());
      client = manager.clientFor('em1')!;
    });

    tearDownAll(() async {
      await manager.logout('em1');
    });

    test('power state read from the live system', () async {
      final PowerService svc = PowerService(
        client: client,
        systemId: 'em1',
        systemResourceUri: '/redfish/v1/Systems/437XR1138R2',
      );
      final PowerState state = await svc.fetchPowerState();
      expect(state, PowerState.on);
    });

    test('reset action accepted (202) without weakening TLS', () async {
      final PowerService svc = PowerService(
        client: client,
        systemId: 'em1',
        systemResourceUri: '/redfish/v1/Systems/437XR1138R2',
      );
      // Emulator grants reset; the client must normalize success (2xx) and
      // never treat a non-2xx as success.
      await svc.reset(ResetType.gracefulRestart);
      // State should still be readable afterwards.
      final PowerState state = await svc.fetchPowerState();
      expect(state, isA<PowerState>());
    });

    test('unknown resource maps to a normalized 404 RedfishException',
        () async {
      try {
        await client.getJson('/redfish/v1/NoSuchResource');
        fail('expected a RedfishException for a missing resource');
      } on RedfishException catch (e) {
        expect(e.statusCode, 404);
        expect(e.retryable, isFalse);
      }
    });

    test('unsupported action maps to a normalized 404 RedfishException',
        () async {
      try {
        await client.postJson(
          '/redfish/v1/Systems/437XR1138R2/Actions/ComputerSystem.NoSuch',
          body: <String, dynamic>{'ResetType': 'On'},
        );
        fail('expected a RedfishException for an unknown action');
      } on RedfishException catch (e) {
        expect(e.statusCode, 404);
        expect(e.retryable, isFalse);
      }
    });
  });
}
